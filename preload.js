const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('spinadoc', {
  getInitialFiles: () => ipcRenderer.invoke('file:get-initial'),
  openDialog: () => ipcRenderer.invoke('file:open-dialog'),
  readFile: (p, opts) => ipcRenderer.invoke('file:read', p, opts),
  printSubmit: (task) => ipcRenderer.invoke('print:submit', task),
  printCancel: (id) => ipcRenderer.invoke('print:cancel', id),
  printActive: () => ipcRenderer.invoke('print:active'),
  onPrintProgress: (cb) => ipcRenderer.on('print:progress', (_e, d) => cb(d)),
  // fenêtre de travail cachée (print-worker)
  onWorkerRun: (cb) => ipcRenderer.on('pw:run', (_e, t) => cb(t)),
  onWorkerCancel: (cb) => ipcRenderer.on('pw:cancel', (_e, id) => cb(id)),
  workerProgress: (d) => ipcRenderer.send('pw:progress', d),
  workerJob: (d) => ipcRenderer.invoke('pw:job', d),
  workerDone: (d) => ipcRenderer.send('pw:done', d),
  workerReady: () => ipcRenderer.send('pw:ready'),
  pickDir: (startDir) => ipcRenderer.invoke('file:pick-dir', startDir),
  writeMany: (dir, files) => ipcRenderer.invoke('file:write-many', { dir, files }),
  saveAs: (bytes, suggestedName, originalPath, opts) =>
    ipcRenderer.invoke('file:save-as', { bytes, suggestedName, originalPath, forbid: (opts && opts.forbid) || null }),
  getPathForFile: (file) => webUtils.getPathForFile(file),
  getAbout: () => ipcRenderer.invoke('app:about'),
  diagnostic: () => ipcRenderer.invoke('app:diag'),
  netStats: () => ipcRenderer.invoke('app:net'),
  defaultApps: () => ipcRenderer.invoke('app:default-apps'),
  setDirty: (v) => ipcRenderer.send('doc:dirty', v),
  onOpenFile: (cb) => ipcRenderer.on('open-file', (_e, p) => cb(p)),
  listRecents: () => ipcRenderer.invoke('recents:list'),
  clearRecents: () => ipcRenderer.invoke('recents:clear'),
  removeRecent: (p) => ipcRenderer.invoke('recents:remove', p),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  toggleFullscreen: () => ipcRenderer.invoke('win:toggle-fullscreen'),
  libList: () => ipcRenderer.invoke('lib:list'),
  libAdd: (entry, bytes) => ipcRenderer.invoke('lib:add', { entry, bytes }),
  libRename: (id, name) => ipcRenderer.invoke('lib:rename', { id, name }),
  libRemove: (id) => ipcRenderer.invoke('lib:remove', id),
  saveText: (text, suggestedName, filterName, ext) => ipcRenderer.invoke('file:save-text', { text, suggestedName, filterName, ext }),
  measureLoad: (p) => ipcRenderer.invoke('measure:load', p),
  measureSave: (p, data) => ipcRenderer.invoke('measure:save', { path: p, data }),
  printPrinters: () => ipcRenderer.invoke('print:printers'),
  printCaps: (name) => ipcRenderer.invoke('print:caps', name),
  printSend: (jobs, opts) => ipcRenderer.invoke('print:send', { jobs, opts }),
  printProps: (name) => ipcRenderer.invoke('print:props', name),
  openImages: () => ipcRenderer.invoke('file:open-images'),
  readImage: (p) => ipcRenderer.invoke('file:read-image', p),
  clipboardImage: () => ipcRenderer.invoke('clipboard:image'),
  onRequestClose: (cb) => ipcRenderer.on('app:request-close', () => cb()),
  confirmClose: () => ipcRenderer.send('app:close-confirmed'),
  isFullscreen: () => ipcRenderer.invoke('win:is-fullscreen'),
});
